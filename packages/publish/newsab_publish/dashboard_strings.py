"""The dev-shell dashboard's own UI copy, in the halo's nine languages.

Distinct from ``site_strings.py`` (the reader-facing production site) and from each
topic's ``review_locale`` (the language that topic's touchpoint two is read and signed
in, which its manifest names and which the language button never moves).  This table is
purely cosmetic: which language the *tool* speaks to whoever is sitting at the keyboard,
chosen with the top-right language button and remembered in that browser's
``localStorage``.

Same pattern as ``site_strings.py``: a symmetric ``dict[locale, dict[key, str]]`` asserted
at import time, keyed by ``newsab_schema.HALO_LOCALES`` (the nine-language commitment the
home page's halo makes) rather than by ``SITE_LOCALES`` — the dashboard never had a
"live languages" gate to respect, so it goes straight to the full set.

A handful of values carry inline HTML (``<code>``, ``<strong>``) because the dashboard's
renderer builds its cards with plain string interpolation, not a template engine; every
locale must keep the same tags in the same places, which is a case-by-case translation
concern rather than something this module can check for.
"""


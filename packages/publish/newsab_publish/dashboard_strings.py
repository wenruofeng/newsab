def dashboard_strings(locale: str) -> Mapping[str, str]:
    """Return immutable dashboard copy; unsupported locales fail instead of half-localizing."""
    canonical = normalize_lang(locale)
    try:
        return MappingProxyType(_STRINGS[canonical])
    except KeyError as exc:
        raise ValueError(f"unsupported dashboard locale: {canonical}") from exc
